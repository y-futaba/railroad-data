@dataclass(frozen=True, slots=True)
class ResolvedLineAliases:
    """解決済みの事業者通称・運行サービス名・路線通称を保持する値オブジェクト。"""

    co_alias: str
    service: str
    line_alias: str
    service_overridden: bool = False


def resolve_line_aliases(co: str, line: str) -> ResolvedLineAliases:
    """`co -> service -> line -> (co, line)` の優先順で通称を解決する。"""
    co_alias = CO_ALIASES.get(co, co)
    default_service = SERVICES.get(co_alias, co_alias)
    default_line_alias = LINE_ALIASES.get(line, line)

    if (co, line) in SERVICE_LINE_ALIASES:
        override_service, override_line_alias = SERVICE_LINE_ALIASES[(co, line)]
        return ResolvedLineAliases(
            co_alias=co_alias,
            service=override_service,
            line_alias=override_line_alias,
            service_overridden=(override_service != default_service),
        )

    return ResolvedLineAliases(
        co_alias=co_alias,
        service=default_service,
        line_alias=default_line_alias,
        service_overridden=False,
    )
